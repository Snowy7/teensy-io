from enum import IntEnum


class PacketType(IntEnum):
    COMMAND = 0x01
    ACK = 0x02
    NACK = 0x03
    DATA = 0x04
    EVENT = 0x05
    TELEMETRY = 0x06
    ERROR = 0x07


class CommandId(IntEnum):
    PING = 0x01
    GET_INFO = 0x02
    HEARTBEAT = 0x03
    RESET_CONFIG = 0x04

    CONFIG_DIGITAL_INPUT = 0x10
    CONFIG_DIGITAL_OUTPUT = 0x11
    DIGITAL_READ = 0x12
    DIGITAL_WRITE = 0x13

    CONFIG_PWM = 0x20
    PWM_WRITE = 0x21
    PWM_DISABLE = 0x22

    CONFIG_ANALOG = 0x30
    ANALOG_READ = 0x31

    CONFIG_COUNTER = 0x40
    COUNTER_READ = 0x41
    COUNTER_RESET = 0x42
    COUNTER_FREQUENCY = 0x43

    CONFIG_ENCODER = 0x50
    ENCODER_READ = 0x51
    ENCODER_RESET = 0x52

    SUBSCRIBE = 0x60
    UNSUBSCRIBE = 0x61
    TELEMETRY_FRAME = 0x62

    EMERGENCY_STOP = 0xF0
    CLEAR_EMERGENCY_STOP = 0xF1


class ErrorCode(IntEnum):
    OK = 0x00
    UNKNOWN_COMMAND = 0x01
    INVALID_PAYLOAD = 0x02
    INVALID_PIN = 0x03
    INVALID_MODE = 0x04
    EMERGENCY_STOP_ACTIVE = 0x05
    RESOURCE_UNAVAILABLE = 0x06
